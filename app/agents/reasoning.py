from app.agents.reflector import find_violations
from app.models.state import AgentState
from app.services.osrm_service import calculate_route_osrm, calculate_routes_osrm

def route_reasoning_agent(state: AgentState) -> AgentState:
    """
    Route Reasoning Agent:
    Calculates candidate route polyline using OSRM engine with any detour waypoints generated by Reflector.

    On the first iteration there are no waypoints yet, so OSRM's own alternative routes are
    requested as well and the one violating the fewest perceived hazards wins. The proposed system
    therefore never starts from a worse route than picking an alternative would give.
    """
    logs = state["logs"]
    refl_cnt = state["reflection_count"]
    waypoints = state.get("waypoints", [])
    logs.append(
        f"[2. Reasoning Agent] Calculating route (Iteration {refl_cnt}, {len(waypoints)} detour waypoint(s))..."
    )

    if waypoints:
        route = calculate_route_osrm(state["origin"], state["destination"], waypoints=waypoints)
    else:
        hazards = state["avoid_points"]

        def score(candidate):
            v = find_violations(candidate["coordinates"], hazards)
            return (len(v), sum(x["hazard"]["radius_m"] - x["distance_m"] for x in v), candidate["distance_m"])

        candidates = calculate_routes_osrm(state["origin"], state["destination"], alternatives=True)
        route = min(candidates, key=score)
        if len(candidates) > 1:
            logs.append(f"  -> OSRM offered {len(candidates)} route(s); kept the one violating the fewest hazards")

    state["current_route"] = route
    logs.append(f"  -> Generated Polyline: Distance = {route['distance_m']/1000.0:.2f} km, Duration = {route['duration_s']/60.0:.1f} mins")
    return state
